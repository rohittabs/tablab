// Makes js/ui/glyphs.js: the outlines of the music symbols the notation view draws (clef, accidentals,
// rests, noteheads and flags), taken from the Noto Music font so they look right at any size.
//
// Run once, only when the set of symbols changes:
//   npm pack @fontsource/noto-music@5.3.0 opentype.js@2.0.0, unpack both, then
//   node tools/make-glyphs.mjs <path to noto-music-music-400-normal.woff> <path to opentype.mjs>
//
// Noto Music is Copyright 2022 The Noto Project Authors, under the SIL Open Font License 1.1
// (assets/fonts/NotoMusic-OFL.txt). The outlines in glyphs.js stay under that license.

import { readFileSync, writeFileSync } from 'node:fs';

const [fontPath, opentypePath] = process.argv.slice(2);
const opentype = await import(new URL(opentypePath, `file://${process.cwd()}/`).href);
const buf = readFileSync(fontPath);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const CODES = {
  gClef: 0x1d11e,
  flat: 0x266d,
  natural: 0x266e,
  sharp: 0x266f,
  rest1: 0x1d13b,
  rest2: 0x1d13c,
  rest4: 0x1d13d,
  rest8: 0x1d13e,
  rest16: 0x1d13f,
  rest32: 0x1d140,
  headBlack: 0x1d158,
  headVoid: 0x1d157,
  headWhole: 0x1d15d,
  flag1: 0x1d16e,
  flag2: 0x1d16f,
  flag3: 0x1d170,
};

let out = `// Generated by tools/make-glyphs.mjs. Do not edit by hand.
// Music symbol outlines from Noto Music, Copyright 2022 The Noto Project Authors,
// licensed under the SIL Open Font License 1.1 (assets/fonts/NotoMusic-OFL.txt).
//
// Units: 250 to a staff space, y pointing down, origin on the bottom line of the staff
// (as the font places them). w: advance width. box: [x1, y1, x2, y2] in the same units.

export const GLYPHS = {
`;
for (const [name, code] of Object.entries(CODES)) {
  const g = font.charToGlyph(String.fromCodePoint(code));
  const path = g.getPath(0, 0, font.unitsPerEm);
  const d = path.toPathData(0);
  const bb = path.getBoundingBox();
  out += `  ${name}: { w: ${g.advanceWidth}, box: [${[bb.x1, bb.y1, bb.x2, bb.y2].map((v) => Math.round(v)).join(', ')}], d: '${d}' },\n`;
}
out += '};\n';
writeFileSync(new URL('../js/ui/glyphs.js', import.meta.url), out);
console.log('wrote js/ui/glyphs.js', out.length, 'bytes');
